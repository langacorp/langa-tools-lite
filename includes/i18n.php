/**
 * Quick string getter: langa_t('forms', 'submit') → 'Invia richiesta'
 */
function langa_t($group, $key, $vars = array()) {
  $t = langa_tools_client_i18n($group);
  $s = isset($t[$key]) ? (string)$t[$key] : '';
  if ($s === '') return '';
  if (!empty($vars)) {
    foreach ($vars as $k => $v) {
      $s = str_replace('{' . $k . '}', (string)$v, $s);
    }
  }
  return $s;
}

