/**
 * Unified frontend i18n — forms, maintenance, email confirmation.
 * Supported: it, en, es, fr, de, ru, ar.  Fallback: en.
 */

function langa_tools_client_detect_lang() {
  static $cached = null;
  if ($cached !== null) return $cached;

  $supported = array('it','en','es','fr','de','ru','pt','ar');

  // Polylang
  if (function_exists('pll_current_language')) {
    $l = pll_current_language('slug');
    if (is_string($l) && $l !== '') {
      $code = substr(strtolower(trim($l)), 0, 2);
      if (in_array($code, $supported, true)) { $cached = $code; return $cached; }
    }
  }
  // WPML
  if (defined('ICL_LANGUAGE_CODE') && is_string(ICL_LANGUAGE_CODE) && ICL_LANGUAGE_CODE !== '') {
    $code = substr(strtolower(ICL_LANGUAGE_CODE), 0, 2);
    if (in_array($code, $supported, true)) { $cached = $code; return $cached; }
  }
  // WP locale
  $locale = function_exists('determine_locale') ? determine_locale() : get_locale();
  if (is_string($locale) && $locale !== '') {
    $code = substr(strtolower($locale), 0, 2);
    if (in_array($code, $supported, true)) { $cached = $code; return $cached; }
  }
  // Browser Accept-Language (frontend only, not during AJAX to avoid mixing admin/visitor lang)
  if (!is_admin() && !wp_doing_ajax() && !empty($_SERVER['HTTP_ACCEPT_LANGUAGE'])) {
    $raw = strtolower(sanitize_text_field(wp_unslash($_SERVER['HTTP_ACCEPT_LANGUAGE'])));
    if (preg_match_all('/([a-z]{2})(?:-[a-z]{2})?(?:;q=([0-9.]+))?/', $raw, $m, PREG_SET_ORDER)) {
      $best = ''; $best_q = -1.0;
      foreach ($m as $match) {
        $c = $match[1];
        $q = isset($match[2]) && $match[2] !== '' ? (float)$match[2] : 1.0;
        if (in_array($c, $supported, true) && $q > $best_q) { $best = $c; $best_q = $q; }
      }
      if ($best !== '') { $cached = $best; return $cached; }
    }
  }
  $cached = 'en';
  return $cached;
}

